"""Generate JSON Schema and C# types from protocol/messages.py.

Run from hub/:  uv run python -m protocol.export
C# output needs com.unity.nuget.newtonsoft-json in the Quest project.
"""

from __future__ import annotations

import json
import types
import typing
from enum import Enum
from pathlib import Path

from pydantic import BaseModel, TypeAdapter

from . import messages as m

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_DIR = ROOT / "hub" / "protocol" / "schema"
CS_PATH = ROOT / "quest" / "Assets" / "Cocktail" / "Protocol" / "Messages.cs"

MODELS = [
    m.Hello, m.AudioChunk, m.VideoFrame, m.PoseSample, m.InputEvent,
    m.SetMode, m.SetVolumes, m.AckAlert,
    m.Source, m.SourcesUpdated, m.StateChanged, m.TargetUpdated, m.AlertFired,
    m.ReplayReady, m.Metrics, m.AudioOut,
]
ENUMS = [m.Action, m.Mode, m.TrackState, m.BearingSource, m.HubState]
UNIONS = {"PoseChannelMessage": m.PoseChannelMessage, "Command": m.Command, "HubEvent": m.HubEvent}


def cs_type(ann) -> str:
    origin = typing.get_origin(ann)
    args = typing.get_args(ann)
    if origin in (typing.Union, types.UnionType):
        inner = [a for a in args if a is not type(None)]
        t = cs_type(inner[0])
        return t if t.endswith("?") or t in ("string",) or t.endswith("]") or t.startswith("List") or t.startswith("Dictionary") else t + "?"
    if origin is typing.Literal:
        return cs_type(type(args[0]))
    if origin is tuple:
        return cs_type(args[0]) + "[]"
    if origin is list:
        return f"List<{cs_type(args[0])}>"
    if origin is dict:
        return f"Dictionary<{cs_type(args[0])}, {cs_type(args[1])}>"
    if isinstance(ann, type) and issubclass(ann, Enum):
        return ann.__name__
    if isinstance(ann, type) and issubclass(ann, BaseModel):
        return ann.__name__
    return {int: "long", float: "float", str: "string", bool: "bool"}[ann]


def pascal(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("_"))


def gen_cs() -> str:
    out = [
        "// GENERATED by hub/protocol/export.py from hub/protocol/messages.py. Do not edit.",
        "using System.Collections.Generic;",
        "using System.Runtime.Serialization;",
        "using Newtonsoft.Json;",
        "using Newtonsoft.Json.Converters;",
        "",
        "namespace Cocktail.Protocol",
        "{",
        "    public static class ProtocolInfo",
        "    {",
        f'        public const string Version = "{m.PROTOCOL_VERSION}";',
        f"        public const int DefaultPort = {m.DEFAULT_PORT};",
        f'        public const string WsAudioIn = "{m.WS_AUDIO_IN}";',
        f'        public const string WsVideoIn = "{m.WS_VIDEO_IN}";',
        f'        public const string WsPoseIn = "{m.WS_POSE_IN}";',
        f'        public const string WsEvents = "{m.WS_EVENTS}";',
        f'        public const string WsAudioOut = "{m.WS_AUDIO_OUT}";',
        "    }",
        "",
    ]
    for e in ENUMS:
        out.append("    [JsonConverter(typeof(StringEnumConverter))]")
        out.append(f"    public enum {e.__name__}")
        out.append("    {")
        for v in e:
            out.append(f'        [EnumMember(Value = "{v.value}")] {pascal(v.name)},')
        out.append("    }")
        out.append("")
    for model in MODELS:
        out.append(f"    public class {model.__name__}")
        out.append("    {")
        for name, f in model.model_fields.items():
            t = cs_type(f.annotation)
            default = ""
            if isinstance(f.default, str):
                default = f' = "{f.default}";'
            elif isinstance(f.default, Enum):
                default = f" = {type(f.default).__name__}.{pascal(f.default.name)};"
            elif isinstance(f.default, bool):
                default = f" = {str(f.default).lower()};"
            elif isinstance(f.default, (int, float)) and not isinstance(f.default, bool):
                default = f" = {f.default}{'f' if t.startswith('float') else ''};"
            out.append(f'        [JsonProperty("{name}")] public {t} {pascal(name)}{default or ";"}')
        out.append("    }")
        out.append("")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> None:
    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    for model in MODELS:
        (SCHEMA_DIR / f"{model.__name__}.json").write_text(json.dumps(model.model_json_schema(), indent=2) + "\n")
    for name, u in UNIONS.items():
        (SCHEMA_DIR / f"{name}.json").write_text(json.dumps(TypeAdapter(u).json_schema(), indent=2) + "\n")
    CS_PATH.parent.mkdir(parents=True, exist_ok=True)
    CS_PATH.write_text(gen_cs())
    print(f"schemas -> {SCHEMA_DIR}\nC# -> {CS_PATH}")


if __name__ == "__main__":
    main()
